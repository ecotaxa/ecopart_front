import { describe, it, expect, beforeEach, vi } from 'vitest';
import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { Routes, Route } from 'react-router-dom';
import { http, HttpResponse } from 'msw';

import ProjectsPage from './ProjectsPage';
import { renderWithRouter } from '@/test/utils';
import { server } from '@/test/msw/server';
import { loginAsAdmin, loginAsUser } from '@/test/helpers/auth.helpers';
import { answerConfirmDialogs } from '@/test/helpers/confirm.helpers';

// Helper to mock the complex POST search request
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const mockProjectsResponse = (projects: any[], total = projects.length) => {
    server.use(
        http.post('*/projects/searches', () => {
            return HttpResponse.json({
                search_info: { total, page: 1, limit: 10 },
                projects
            });
        })
    );
};

// Dummy project data for testing
const MOCK_PROJECT_1 = {
    project_id: 101,
    project_title: 'Ocean Deep Exploration',
    project_acronym: 'ODE',
    instrument_model: 'UVP5HD',
    ecotaxa_project_name: 'ecotaxa_ode',
    root_folder_path: '/data/ode',
    managers: [{ user_id: 1 }],
    members: [],
    qc_state: 'validated'
};

const MOCK_PROJECT_2 = {
    project_id: 202,
    project_title: 'Coastal Monitoring',
    project_acronym: 'COAST',
    instrument_model: 'UVP6LP',
    ecotaxa_project_name: null,
    root_folder_path: '/data/coast',
    managers: [],
    members: [{ user_id: 1 }],
    qc_state: 'warning'
};

describe('ProjectsPage (Functional)', () => {

    beforeEach(() => {
        loginAsUser();
        vi.clearAllMocks();
    });

    // TC-G1: Initial Data Loading
    it('TC-G1: should load and display projects in the DataGrid', async () => {
        mockProjectsResponse([MOCK_PROJECT_1, MOCK_PROJECT_2]);

        renderWithRouter(
            <Routes>
                <Route path="/projects" element={<ProjectsPage />} />
            </Routes>,
            { route: '/projects' }
        );

        expect(await screen.findByText('Ocean Deep Exploration')).toBeInTheDocument();
        expect(screen.getByText('Coastal Monitoring')).toBeInTheDocument();

        const chipManager = screen.getAllByText('Manager');
        expect(chipManager.length).toBeGreaterThan(0);

        expect(screen.getByText('Not linked')).toBeInTheDocument();
    });

    // TC-G2: Error Handling
    it('TC-G2: should display an error alert if the API fails', async () => {
        // Force API failure
        server.use(
            http.post('*/projects/searches', () => {
                // Our HTTP client intercepts non-2xx responses and throws an Error
                // whose message is typically "HTTP Error: 500" if no JSON body is provided.
                // We test against this actual observed behavior.
                return new HttpResponse(null, { status: 500 });
            })
        );

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        const alert = await screen.findByRole('alert');
        expect(within(alert).getByText(/Failed to load projects from server/i)).toBeInTheDocument();

        // Check for the specific error message generated by the HTTP client
        expect(within(alert).getByText(/HTTP Error: 500/i)).toBeInTheDocument();
    });

    // TC-G3: Filtering & Searching (UI State)
    it('TC-G3: should update UI when filters and search attributes are changed', async () => {
        const user = userEvent.setup();
        mockProjectsResponse([]);

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        const searchInput = await screen.findByPlaceholderText('Search...');
        await user.type(searchInput, 'Tara');
        expect(searchInput).toHaveValue('Tara');

        // The default text is "All My Projects" based on the Hook's initial state
        const filterButton = screen.getByRole('button', { name: 'All My Projects' });
        await user.click(filterButton);

        const validatedMenuItem = screen.getByRole('menuitem', { name: 'Validated QC' });
        await user.click(validatedMenuItem);

        expect(screen.getByRole('button', { name: 'Filter: Validated' })).toBeInTheDocument();
    }, 15000);

    // TC-G4: Row Selection & Explore Navigation
    it('TC-G4: should allow row selection and navigate to explore with selected IDs', async () => {
        const user = userEvent.setup();
        mockProjectsResponse([MOCK_PROJECT_1, MOCK_PROJECT_2]);

        renderWithRouter(
            <Routes>
                <Route path="/projects" element={<ProjectsPage />} />
                <Route path="/explore" element={<h1>Explore Page Mock</h1>} />
            </Routes>,
            { route: '/projects' }
        );

        await screen.findByText('Ocean Deep Exploration');

        const rowCheckboxes = screen.getAllByLabelText(/Select row/i);
        await user.click(rowCheckboxes[0]);

        expect(screen.getByText('1 items selected')).toBeInTheDocument();

        const exploreButton = screen.getByRole('button', { name: /EXPLORE SELECTION/i });
        await user.click(exploreButton);

        expect(await screen.findByText('Explore Page Mock')).toBeInTheDocument();
    }, 15000);

    // TC-G5: Row Click Navigation
    it('TC-G5: should navigate to project details when a row is clicked', async () => {
        const user = userEvent.setup();
        mockProjectsResponse([MOCK_PROJECT_1]);

        renderWithRouter(
            <Routes>
                <Route path="/projects" element={<ProjectsPage />} />
                <Route path="/projects/:id/:tabName?" element={<h1>Project Details Mock</h1>} />
            </Routes>,
            { route: '/projects' }
        );

        const projectCell = await screen.findByText('Ocean Deep Exploration');

        await user.click(projectCell);

        expect(await screen.findByText('Project Details Mock')).toBeInTheDocument();
    }, 15000);

    // TC-G4b: Delete a managed project from the selection bar
    it('TC-G4b: should delete the selected managed project after confirmation', async () => {
        const user = userEvent.setup();
        const deletedIds: string[] = [];

        mockProjectsResponse([MOCK_PROJECT_1, MOCK_PROJECT_2]);
        server.use(
            http.delete('*/projects/:projectId/', ({ params }) => {
                deletedIds.push(String(params.projectId));
                return HttpResponse.json({ message: 'deleted' });
            })
        );
        const confirmSpy = answerConfirmDialogs(true);

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        await screen.findByText('Ocean Deep Exploration');

        // MOCK_PROJECT_1 is managed by the logged-in user (user_id 1).
        const rowCheckboxes = screen.getAllByLabelText(/Select row/i);
        await user.click(rowCheckboxes[0]);

        const deleteButton = screen.getByRole('button', { name: /DELETE/i });
        expect(deleteButton).toBeEnabled();

        await user.click(deleteButton);

        expect(confirmSpy).toHaveBeenCalled();
        expect(await screen.findByText(/Project\(s\) deleted\./i)).toBeInTheDocument();
        expect(deletedIds).toEqual(['101']);

        confirmSpy.mockRestore();
    }, 15000);

    // TC-G4c: Delete stays disabled for a project the user is only a member of
    it('TC-G4c: should keep DELETE disabled when the selection is not managed by the user', async () => {
        const user = userEvent.setup();
        mockProjectsResponse([MOCK_PROJECT_1, MOCK_PROJECT_2]);

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        await screen.findByText('Coastal Monitoring');

        // Nothing selected yet: the action is unavailable.
        expect(screen.getByRole('button', { name: /DELETE/i })).toBeDisabled();

        // MOCK_PROJECT_2 only lists the user as a member.
        const rowCheckboxes = screen.getAllByLabelText(/Select row/i);
        await user.click(rowCheckboxes[1]);

        expect(screen.getByText('1 items selected')).toBeInTheDocument();
        expect(screen.getByRole('button', { name: /DELETE/i })).toBeDisabled();
    }, 15000);

    // TC-G6: Projects Pagination & Query Sync
    it('TC-G6: should request next page and render new rows when pagination changes', async () => {
        const user = userEvent.setup();
        const requestedPages: string[] = [];
        const requestedSortValues: string[] = [];

        server.use(
            http.post('*/projects/searches*', ({ request }) => {
                const url = new URL(request.url);
                const page = url.searchParams.get('page') ?? '1';
                const sortBy = url.searchParams.get('sort_by') ?? '';
                requestedPages.push(page);
                requestedSortValues.push(sortBy);

                if (page === '2') {
                    return HttpResponse.json({
                        search_info: { total: 15, page: 2, limit: 10 },
                        projects: [{
                            ...MOCK_PROJECT_2,
                            project_id: 303,
                            project_title: 'Page Two Project'
                        }]
                    });
                }

                return HttpResponse.json({
                    search_info: { total: 15, page: 1, limit: 10 },
                    projects: [MOCK_PROJECT_1]
                });
            })
        );

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        expect(await screen.findByText('Ocean Deep Exploration')).toBeInTheDocument();

        const nextPageButton = screen.getByRole('button', { name: /Go to next page/i });
        await user.click(nextPageButton);

        expect(await screen.findByText('Page Two Project')).toBeInTheDocument();
        expect(requestedPages).toContain('1');
        expect(requestedPages).toContain('2');
        expect(requestedSortValues.every((value) => value === 'desc(project_id)')).toBe(true);
    }, 15000);


    // TC-G8: every row shows the privacy status computed by the backend, and the role of the user on it
    it('TC-G8: shows a Privacy chip and the Privilege of the user on each project', async () => {
        mockProjectsResponse([
            { ...MOCK_PROJECT_1, privacy_status: 'open' },
            { ...MOCK_PROJECT_2, privacy_status: 'visible' },
            // An old backend without privacy_status: read as private.
            { ...MOCK_PROJECT_2, project_id: 303, project_title: 'Other Project', members: [], managers: [{ user_id: 2 }] },
        ]);

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        expect(await screen.findByText('Other Project')).toBeInTheDocument();
        expect(within(screen.getByRole('columnheader', { name: 'Privacy' })).getByTestId('InfoOutlinedIcon')).toBeInTheDocument();
        expect(screen.getByText('Open')).toBeInTheDocument();
        expect(screen.getByText('Visible')).toBeInTheDocument();
        expect(screen.getByText('Private')).toBeInTheDocument();
        expect(screen.getByText('Manager')).toBeInTheDocument();
        expect(screen.getByText('Member')).toBeInTheDocument();
    });

    // TC-G8b: an admin holds every privilege, and may delete any selected project
    it('TC-G8b: labels an admin as Admin and lets them delete any project', async () => {
        const user = userEvent.setup();
        loginAsAdmin();
        mockProjectsResponse([{ ...MOCK_PROJECT_2, managers: [{ user_id: 2 }], members: [] }]);

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        await screen.findByText('Coastal Monitoring');
        expect(screen.getByText('Admin')).toBeInTheDocument();

        await user.click(screen.getAllByLabelText(/Select row/i)[0]);
        expect(screen.getByRole('button', { name: /DELETE/i })).toBeEnabled();
    }, 15000);

    // TC-G9: the "All projects" scope lists every project, not only the user's
    it('TC-G9: drops the for_managing filter in the "All projects" scope', async () => {
        const user = userEvent.setup();
        const sentFilters: unknown[] = [];
        server.use(
            http.post('*/projects/searches', async ({ request }) => {
                sentFilters.push(await request.json());
                return HttpResponse.json({ search_info: { total: 0, page: 1, limit: 10 }, projects: [] });
            })
        );

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        await waitFor(() => expect(sentFilters).toContainEqual([{ field: 'for_managing', operator: '=', value: true }]));
        expect(screen.getByText('Projects in which you have privilege')).toBeInTheDocument();

        await user.click(screen.getByRole('button', { name: 'All My Projects' }));
        await user.click(screen.getByRole('menuitem', { name: 'All projects' }));

        expect(screen.getByRole('button', { name: 'All projects' })).toBeInTheDocument();
        expect(screen.getByText(/Every project; data access depends on the privacy status and your privilege/i)).toBeInTheDocument();
        await waitFor(() => expect(sentFilters).toContainEqual([]));
    }, 15000);

    // TC-G10: the Privacy filter applies on top of every scope
    it('TC-G10: sends a privacy_status filter with the scope, and keeps it when the scope changes', async () => {
        const user = userEvent.setup();
        const sentFilters: unknown[] = [];
        server.use(
            http.post('*/projects/searches', async ({ request }) => {
                sentFilters.push(await request.json());
                return HttpResponse.json({ search_info: { total: 0, page: 1, limit: 10 }, projects: [] });
            })
        );

        renderWithRouter(<ProjectsPage />, { route: '/projects' });

        await user.click(await screen.findByRole('combobox', { name: 'Privacy' }));
        expect(screen.getAllByRole('option').map((option) => option.textContent)).toEqual(['Any', 'Private', 'Visible', 'Public', 'Open']);
        await user.click(screen.getByRole('option', { name: 'Open' }));

        await waitFor(() => expect(sentFilters).toContainEqual([
            { field: 'for_managing', operator: '=', value: true },
            { field: 'privacy_status', operator: '=', value: 'open' },
        ]));

        await user.click(screen.getByRole('button', { name: 'All My Projects' }));
        await user.click(screen.getByRole('menuitem', { name: 'All projects' }));
        await waitFor(() => expect(sentFilters).toContainEqual([{ field: 'privacy_status', operator: '=', value: 'open' }]));

        await user.click(screen.getByRole('combobox', { name: 'Privacy' }));
        await user.click(screen.getByRole('option', { name: 'Any' }));
        await waitFor(() => expect(sentFilters[sentFilters.length - 1]).toEqual([]));
    }, 15000);
});
